/* Center Stage (the software tracking of CameraController.swift and the
 * transform of CameraOverlay.swift): find the largest face a few times a
 * second, smooth it, and pan and zoom the camera picture so the face stays
 * centred in the mask, without ever showing the black background.
 *
 * Faces come from pico (vendor/pico, MIT, Nenad Markus) run on a grayscale
 * copy of the 640 px preview frames in the camera streaming thread; results
 * reach the main loop through an idle callback. Coordinates are top-left
 * based: Vision's are bottom-left, so the head-room bias moves up (smaller
 * y) and the 0.92 ceiling becomes a 0.08 floor. */

#include <math.h>
#include "youcam.h"
#include "vendor/pico/picornt.h"
#include "facefinder.h"   /* Generated by the Makefile: xxd -i of the cascade. */

#define MOVING_INTERVAL_US 200000   /* 5 Hz while the head moves... */
#define STABLE_INTERVAL_US 500000   /* ...2 Hz once it has stayed still. */
#define STABLE_AFTER 5
#define STABLE_MAX 20
#define STABLE_MOVEMENT 0.015
#define DEADZONE_MOVEMENT 0.012
#define DEADZONE_WIDTH 0.02
#define SMOOTHING 0.22
#define LOST_AFTER_MISSES 5         /* About a second without a face. */
#define ANIMATION_US 240000
#define SOFT_KNEE 0.95
#define MIN_PAN_POINTS 0.5
#define MIN_QUALITY 5.0f            /* As pico's sample.c. */
#define MAX_DETECTIONS 2048
#define MIN_FACE_PX 40
#define PICO_SCALE 1.1f
#define PICO_STRIDE 0.1f

static struct {
    /* Camera streaming thread. */
    gint64 last_detection;
    int stable, has_last;
    double last_x, last_y;
    guint8 *gray;
    size_t gray_size;
    /* Main thread. */
    stage_face face;
    int has_face, misses;
    stage_transform from, shown;
    gint64 start;
    void (*on_change)(void);
} S = {.from = {1, 0, 0}, .shown = {1, 0, 0}};

/* ------------------------------------------------------------ pure logic */

/* Slows the pan near the edge of the video instead of stopping dead. */
double stage_soft_clamp(double value, double max) {
    return max > MIN_PAN_POINTS ? max * tanh(value / max * SOFT_KNEE) : 0;
}

/* Built-in webcam zoom: a little more in a rectangle, less when close. */
double stage_zoom(const stage_face *f, camera_shape shape) {
    double base = shape == SHAPE_RECTANGLE ? 1.28 : 1.10;
    double closeness_penalty = fmax(0, (f->h - 0.32) * 0.70);
    return fmax(1.02, base - closeness_penalty);
}

/* Ignores small movements, then follows with exponential smoothing.
 * Returns 0 when the new face is inside the deadzone. */
int stage_smooth(stage_face *smoothed, int has_smoothed, stage_face f) {
    if (!has_smoothed) {
        *smoothed = f;
        return 1;
    }
    if (hypot(f.cx - smoothed->cx, f.cy - smoothed->cy) < DEADZONE_MOVEMENT &&
        fabs(f.w - smoothed->w) < DEADZONE_WIDTH) return 0;
    smoothed->cx += (f.cx - smoothed->cx) * SMOOTHING;
    smoothed->cy += (f.cy - smoothed->cy) * SMOOTHING;
    smoothed->w += (f.w - smoothed->w) * SMOOTHING;
    smoothed->h += (f.h - smoothed->h) * SMOOTHING;
    return 1;
}

/* Transform that brings the face to the centre of a w x h mask, panning no
 * further than the zoomed 16:9 canvas allows. NULL face: identity. */
stage_transform stage_transform_for(const stage_face *f, double w, double h, camera_shape shape, int mirrored) {
    if (!f || w <= 0 || h <= 0) return STAGE_IDENTITY;
    double cw, ch;
    stage_canvas(w, h, &cw, &ch);
    stage_transform t;
    t.zoom = stage_zoom(f, shape);
    double visual_x = mirrored ? 1 - f->cx : f->cx;
    double visual_y = fmax(1 - 0.92, f->cy - f->h * (shape == SHAPE_CIRCLE ? 0.02 : 0.04));
    double scaled_w = cw * t.zoom, scaled_h = ch * t.zoom;
    t.x = stage_soft_clamp((0.5 - visual_x) * scaled_w, fmax(0, (scaled_w - w) / 2)) / w;
    t.y = stage_soft_clamp((0.5 - visual_y) * scaled_h, fmax(0, (scaled_h - h) / 2)) / h;
    return t;
}

/* Largest confident face in a grayscale image, normalized. */
int stage_detect(const guint8 *gray, int w, int h, stage_face *out) {
    static float rcsq[4 * MAX_DETECTIONS];   /* One detector thread at a time. */
    int n = find_objects(rcsq, MAX_DETECTIONS, facefinder, 0.0f, (void *)gray, h, w, w,
                         PICO_SCALE, PICO_STRIDE, MIN_FACE_PX, MIN(w, h));
    n = cluster_detections(rcsq, n);
    int best = -1;
    for (int i = 0; i < n; i++)
        if (rcsq[4 * i + 3] >= MIN_QUALITY && (best < 0 || rcsq[4 * i + 2] > rcsq[4 * best + 2])) best = i;
    if (best < 0) return 0;
    float row = rcsq[4 * best], col = rcsq[4 * best + 1], size = rcsq[4 * best + 2];
    *out = (stage_face){col / w, row / h, size / w, size / h};
    return 1;
}

/* ------------------------------------------------------ streaming thread */

typedef struct { int found; stage_face face; } detection;

static gboolean deliver(gpointer data) {
    detection *d = data;
    if (Prefs.center_stage) center_stage_update(d->found ? &d->face : NULL);
    g_free(d);
    return G_SOURCE_REMOVE;
}

/* Called for every camera frame (BGRx); detects at 5 Hz, or 2 Hz when still. */
void center_stage_feed(const guint8 *bgrx, int w, int h, int stride) {
    if (!Prefs.center_stage) return;
    gint64 now = g_get_monotonic_time();
    gint64 interval = S.stable >= STABLE_AFTER ? STABLE_INTERVAL_US : MOVING_INTERVAL_US;
    if (now - S.last_detection < interval) return;
    S.last_detection = now;
    size_t size = (size_t)w * h;
    if (size > S.gray_size) {
        S.gray = g_realloc(S.gray, size);
        S.gray_size = size;
    }
    for (int y = 0; y < h; y++) {
        const guint8 *p = bgrx + (size_t)y * stride;
        guint8 *g = S.gray + (size_t)y * w;
        for (int x = 0; x < w; x++, p += 4) g[x] = (guint8)((p[0] * 29 + p[1] * 150 + p[2] * 77) >> 8);
    }
    detection *d = g_new0(detection, 1);
    d->found = stage_detect(S.gray, w, h, &d->face);
    if (d->found && S.has_last && hypot(d->face.cx - S.last_x, d->face.cy - S.last_y) < STABLE_MOVEMENT) {
        S.stable = MIN(STABLE_MAX, S.stable + 1);
    } else {
        S.stable = 0;
        S.has_last = d->found;
        S.last_x = d->face.cx;
        S.last_y = d->face.cy;
    }
    g_idle_add(deliver, d);
}

/* ----------------------------------------------------------- main thread */

static void retarget(void) {
    S.from = S.shown;
    S.start = g_get_monotonic_time();
    if (S.on_change) S.on_change();
}

/* A detection result; NULL is a frame without a face. The face counts as
 * lost after a few misses in a row, so a single missed frame does not jump. */
void center_stage_update(const stage_face *f) {
    if (!f) {
        if (!S.has_face || ++S.misses < LOST_AFTER_MISSES) return;
        S.has_face = 0;
    } else {
        S.misses = 0;
        if (!stage_smooth(&S.face, S.has_face, *f)) return;
        S.has_face = 1;
    }
    retarget();
}

/* Center Stage turned off or the camera stopped: back to the plain picture. */
void center_stage_reset(void) {
    S.misses = 0;
    if (!S.has_face) return;
    S.has_face = 0;
    retarget();
}

int center_stage_has_face(void) { return S.has_face; }

int center_stage_animating(void) { return g_get_monotonic_time() - S.start < ANIMATION_US; }

/* The transform to draw now: on its way, over 0.24 s, from where the picture
 * was to where the latest face wants it. */
stage_transform center_stage_now(double w, double h, camera_shape shape, int mirrored) {
    stage_transform to = stage_transform_for(S.has_face ? &S.face : NULL, w, h, shape, mirrored);
    double p = fmin(1, (g_get_monotonic_time() - S.start) / (double)ANIMATION_US);
    p = 1 - pow(1 - p, 3);   /* Cubic ease-out, close to CoreAnimation's easeOut. */
    S.shown = (stage_transform){S.from.zoom + (to.zoom - S.from.zoom) * p,
                                S.from.x + (to.x - S.from.x) * p, S.from.y + (to.y - S.from.y) * p};
    return S.shown;
}

void center_stage_init(void (*on_change)(void)) { S.on_change = on_change; }
